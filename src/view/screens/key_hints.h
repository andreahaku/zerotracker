// The tooltip for a key by its English name, or kNothing.
inline const Text& for_key(const char* key) {
    if (key && *key) {
        for (const Entry& e : kKeys) {
            if (std::strcmp(e.key, key) == 0) return e.text;
        }
    }
    return kNothing;
}

